    fun find(lesson: PortalLesson, quarter: Int, faculty: String?): SchoolCourseOffering? {
        if (faculty != "理学部") return null
        val description = java.text.Normalizer.normalize(lesson.description, java.text.Normalizer.Form.NFKC)
        val credits = Regex(" ([0-9.]+)単位$").find(description)?.groupValues?.get(1)?.toBigDecimalOrNull() ?: return null
        val name = description.substringAfter(' ').substringBeforeLast(' ')
            .replace(Regex("【(?:[1-4]Q|前期|後期|前学期|後学期)】"), "").substringBefore("【").replace(Regex("\\s+"), "")
        val terms = rows.filter { it[0] == name && it[1].toBigDecimal().compareTo(credits) == 0 &&
            it[2].toInt() == lesson.day && it[3].toInt() == lesson.period &&
            (it[4] == "${quarter}Q" || it[4] == if (quarter <= 2) "前期" else "後期")
        }.map { it[4] }.distinct()
        return terms.singleOrNull()?.let { SchoolCourseOffering(it, SchoolCampus.MITO) }
    }
